import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import {createServer} from 'node:http';
import {chromium} from '../../tools/playwright.mjs';
import {staticHandler} from '../.storybook/static-server.mjs';

const output=process.env.ASMB_PUBLICATION_OUTPUT,executablePath=process.env.ASMB_BROWSER;
assert(output&&executablePath,'Set ASMB_PUBLICATION_OUTPUT and ASMB_BROWSER.');
await fs.mkdir(output,{recursive:false});
const buildRoot=path.resolve('ui-workshop/storybook-static');
const index=JSON.parse(await fs.readFile(path.join(buildRoot,'index.json'),'utf8'));
const story=Object.values(index.entries).find(item=>item.name==='asTeach — Batch 3 review');
assert(story,'Build the Batch 3 review story first.');
let server,browser,page;
const errors=[],externalRequests=[];
try{
  server=createServer();
  await new Promise((resolve,reject)=>{server.once('error',reject);server.listen(0,'127.0.0.1',resolve);});
  const port=server.address().port,origin=`http://127.0.0.1:${port}`;
  const handler=await staticHandler(buildRoot,port);
  server.on('request',(req,res)=>handler(req,res));
  browser=await chromium.launch({headless:true,executablePath,chromiumSandbox:true,args:['--disable-background-networking']});
  page=await browser.newPage({viewport:{width:1440,height:1000}});page.setDefaultTimeout(8000);
  page.on('pageerror',error=>errors.push(error.message));
  await page.route(/^https?:/,route=>{if(new URL(route.request().url()).origin===origin)return route.continue();externalRequests.push(route.request().url());return route.abort();});
  await page.goto(`${origin}/iframe.html?id=${encodeURIComponent(story.id)}&viewMode=story`);
  const study=page.locator('.teach-study:visible');await study.waitFor();
  const frame=()=>page.evaluate(()=>new Promise(resolve=>requestAnimationFrame(()=>requestAnimationFrame(resolve))));
  await frame();
  const exportButton=study.getByRole('button',{name:'Export',exact:true});
  assert(!(await exportButton.isDisabled()),'Seeded reviewed Student version enables publication previews.');
  await exportButton.click();
  const dialog=page.getByRole('dialog',{name:'Prepare student output',exact:true});await dialog.waitFor();
  assert(await dialog.getByRole('radio',{name:/Export package/}).isChecked());
  assert.equal(await dialog.getByRole('combobox',{name:'Page organization'}).inputValue(),'multiple');
  assert((await dialog.locator('[aria-labelledby="teach-publish-pages"] li').count())>1,'Multipage output exposes more than one derived Student page.');
  assert.match(await dialog.innerText(),/2026-autumn\/README\.md/);
  assert.match(await dialog.innerText(),/No files, repositories or online sites are created/);
  await dialog.getByRole('combobox',{name:'Page organization'}).selectOption('single');await frame();
  assert.equal(await dialog.locator('[aria-labelledby="teach-publish-pages"] li').count(),1);
  await dialog.getByRole('textbox',{name:'Student repository name'}).fill('bad/name');
  await dialog.getByRole('alert').waitFor();assert(await dialog.getByRole('button',{name:'Prepare preview'}).isDisabled());
  await dialog.getByRole('textbox',{name:'Student repository name'}).fill('DES101');
  await dialog.getByRole('radio',{name:/Student repository/}).check();
  assert(await dialog.getByRole('button',{name:'Choose GitHub repository…'}).isDisabled());
  assert.match(await dialog.innerText(),/future reviewed push/);
  await dialog.getByRole('radio',{name:/GitBook package/}).check();
  assert(await dialog.getByRole('button',{name:'Connect GitBook…'}).isDisabled());
  assert.match(await dialog.innerText(),/\.gitbook\.yaml/);assert.match(await dialog.innerText(),/SUMMARY\.md/);
  await dialog.getByRole('button',{name:'Prepare preview'}).click();await dialog.getByRole('status').waitFor();
  await page.screenshot({path:path.join(output,'asteach-batch-3-publication.png'),fullPage:true});
  await page.keyboard.press('Escape');await dialog.waitFor({state:'detached'});assert(await exportButton.evaluate(element=>element===document.activeElement));
  await page.setViewportSize({width:430,height:900});await study.getByRole('button',{name:'GitBook',exact:true}).click();await dialog.waitFor();
  const box=await dialog.boundingBox(),size=page.viewportSize();assert(box&&size&&box.x>=-1&&box.y>=-1&&box.x+box.width<=size.width+1&&box.y+box.height<=size.height+1,'Compact publication dialog fits the viewport.');
  await page.screenshot({path:path.join(output,'asteach-batch-3-publication-compact.png'),fullPage:true});
  assert.deepEqual(errors,[]);assert.deepEqual(externalRequests,[]);
  await fs.writeFile(path.join(output,'result.json'),JSON.stringify({story:story.id,status:'PASS',checks:['multipage mapping','one-page mapping','invalid repository','GitHub boundary','GitBook adapter','focus restoration','compact layout','no external requests']},null,2)+'\n');
  console.log(`PASS|${output}`);
}finally{await browser?.close();await new Promise(resolve=>server?.close(resolve));}
